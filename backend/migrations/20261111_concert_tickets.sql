CREATE TABLE IF NOT EXISTS public.concert_tickets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  order_item_id bigint NOT NULL REFERENCES public.order_items(id) ON DELETE CASCADE,
  attendee_number integer NOT NULL CHECK (attendee_number > 0),
  ticket_code uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  checked_in_at timestamptz,
  checked_in_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (order_item_id, attendee_number)
);

CREATE INDEX IF NOT EXISTS concert_tickets_order_id_idx
  ON public.concert_tickets (order_id);

ALTER TABLE public.concert_tickets ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.issue_concert_tickets_for_paid_order()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.concert_tickets (
    order_id,
    order_item_id,
    attendee_number
  )
  SELECT
    order_item.order_id,
    order_item.id,
    attendee_number.value
  FROM public.order_items AS order_item
  CROSS JOIN LATERAL generate_series(1, order_item.quantity) AS attendee_number(value)
  WHERE order_item.order_id = NEW.id
  ON CONFLICT (order_item_id, attendee_number) DO NOTHING;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS issue_concert_tickets_after_payment
  ON public.orders;

CREATE TRIGGER issue_concert_tickets_after_payment
AFTER UPDATE OF payment_status ON public.orders
FOR EACH ROW
WHEN (
  NEW.payment_status = 'paid'
  AND OLD.payment_status IS DISTINCT FROM 'paid'
)
EXECUTE FUNCTION public.issue_concert_tickets_for_paid_order();

INSERT INTO public.concert_tickets (
  order_id,
  order_item_id,
  attendee_number
)
SELECT
  order_item.order_id,
  order_item.id,
  attendee_number.value
FROM public.orders AS concert_order
JOIN public.order_items AS order_item
  ON order_item.order_id = concert_order.id
CROSS JOIN LATERAL generate_series(1, order_item.quantity) AS attendee_number(value)
WHERE concert_order.payment_status = 'paid'
ON CONFLICT (order_item_id, attendee_number) DO NOTHING;

CREATE OR REPLACE FUNCTION public.consume_concert_ticket(
  p_ticket_code uuid,
  p_admin_id bigint
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  ticket_row public.concert_tickets%ROWTYPE;
BEGIN
  SELECT * INTO ticket_row
  FROM public.concert_tickets
  WHERE ticket_code = p_ticket_code
  FOR UPDATE;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('state', 'invalid');
  END IF;

  IF ticket_row.checked_in_at IS NOT NULL THEN
    RETURN jsonb_build_object(
      'state', 'already_used',
      'checked_in_at', ticket_row.checked_in_at
    );
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public.orders
    WHERE id = ticket_row.order_id
      AND payment_status = 'paid'
  ) THEN
    RETURN jsonb_build_object('state', 'invalid');
  END IF;

  UPDATE public.concert_tickets
  SET checked_in_at = now(),
      checked_in_by = p_admin_id
  WHERE id = ticket_row.id
  RETURNING * INTO ticket_row;

  RETURN jsonb_build_object(
    'state', 'accepted',
    'ticket_id', ticket_row.id,
    'order_id', ticket_row.order_id,
    'order_item_id', ticket_row.order_item_id,
    'attendee_number', ticket_row.attendee_number,
    'checked_in_at', ticket_row.checked_in_at
  );
END;
$$;

REVOKE EXECUTE ON FUNCTION public.consume_concert_ticket(uuid, bigint)
  FROM PUBLIC, anon, authenticated;

GRANT EXECUTE ON FUNCTION public.consume_concert_ticket(uuid, bigint)
  TO service_role;
